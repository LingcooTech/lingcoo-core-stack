#!/usr/bin/env python3
"""Run the compose-runtime fixture on a disposable node workspace; never a customer job.

Input is generated by test/fixtures/compose-runtime.ts. Both scripts are copied to
an isolated directory on a test node. --snapshot also verifies cold volume backup
and isolated restore. Neither mode proves DNS, TLS or trusted publication acceptance.
"""
import hashlib
import importlib.util
import json
from pathlib import Path
import subprocess
import sys
import uuid

job = json.load(sys.stdin)
root = Path(sys.argv[1])
assert not root.exists(), 'Probe requires a new workspace'
assert set(job['compose']['services']) == {'web', 'storage'}, 'Fixture only'
assert job['resources']['memoryMb'] == 256, 'Bounded fixture required'
spec = importlib.util.spec_from_file_location('kernel', Path(__file__).with_name('compose-install.py'))
kernel = importlib.util.module_from_spec(spec)
spec.loader.exec_module(kernel)
kernel.validate(job)
fingerprint = hashlib.sha256(json.dumps(job, sort_keys=True, separators=(',', ':')).encode()).hexdigest()

def docker(args):
    return subprocess.check_output(['docker', *args], timeout=30, stderr=subprocess.DEVNULL).decode().strip()

assert not docker(['ps', '-aq', '--filter', 'label=com.docker.compose.project=' + job['project']]), 'Existing project refused'
jobs_to_cleanup = [job]
try:
    try:
        kernel.execute(job, root, deadline=45)
        raise AssertionError('Fixture must fail its first initialization')
    except RuntimeError as error:
        assert str(error) == 'Installation failed at initialize', 'Unexpected install failure'
    journal = root / job['instanceId'] / 'installation.json'
    failed = json.loads(journal.read_text())
    assert failed['completed'] == ['migrate:0'], 'Migration progress lost'
    evidence = kernel.execute(job, root, deadline=45)
    assert evidence['phase'] == 'runtime_ready' and evidence['imageSource'] == 'registry'
    container = docker(['ps', '-q', '--filter', 'label=com.docker.compose.project=' + job['project'], '--filter', 'label=com.docker.compose.service=web'])
    assert docker(['exec', container, 'cat', '/data/events']).splitlines() == ['migrate', 'initialize']
    assert docker(['exec', container, 'cat', '/data/password']) == job['compose']['services']['web']['environment']['PASSWORD']
    assert docker(['exec', container, 'cat', '/data/literal']) == 'literal$DOLLAR'
    replay = kernel.execute(job, root, deadline=45)
    assert replay == evidence, 'Replay changed evidence'
    assert docker(['exec', container, 'cat', '/data/events']).splitlines() == ['migrate', 'initialize']
    snapshot_result = None
    if '--snapshot' in sys.argv[2:]:
        snapshot_spec = importlib.util.spec_from_file_location('snapshot', Path(__file__).with_name('compose-snapshot.py'))
        snapshots = importlib.util.module_from_spec(snapshot_spec)
        snapshot_spec.loader.exec_module(snapshots)
        snapshot_dir = root / 'cold-snapshot'
        snapshot_result = snapshots.backup(job, root, snapshot_dir)
        assert kernel.execute(job, root, deadline=45)['phase'] == 'runtime_ready', 'Source did not recover after snapshot'
        target = json.loads(json.dumps(job))
        target['instanceId'] = str(uuid.uuid4())
        target['project'] = 'stack-' + target['instanceId'].replace('-', '')
        target['compose']['services']['web']['ports'][0]['published'] += 1
        target['healthUrl'] = job['healthUrl'].replace(':' + str(job['compose']['services']['web']['ports'][0]['published']) + '/', ':' + str(target['compose']['services']['web']['ports'][0]['published']) + '/')
        jobs_to_cleanup.append(target)
        restored = snapshots.restore(target, root, snapshot_dir, snapshot_result['manifestSha256'])
        assert restored['phase'] == 'restored_not_started'
        restored_evidence = kernel.execute(target, root, deadline=45)
        assert restored_evidence['phase'] == 'runtime_ready'
        restored_container = docker(['ps', '-q', '--filter', 'label=com.docker.compose.project=' + target['project'], '--filter', 'label=com.docker.compose.service=web'])
        assert docker(['exec', restored_container, 'cat', '/data/events']).splitlines() == ['migrate', 'initialize'], 'Restore reran initialization'
        assert docker(['exec', restored_container, 'cat', '/data/password']) == job['compose']['services']['web']['environment']['PASSWORD']
        assert docker(['exec', restored_container, 'cat', '/data/literal']) == 'literal$DOLLAR'
        try:
            snapshots.restore(job, root, snapshot_dir, snapshot_result['manifestSha256'])
            raise AssertionError('Source overwrite accepted')
        except ValueError:
            pass
        try:
            snapshots.restore(target, root, snapshot_dir, snapshot_result['manifestSha256'])
            raise AssertionError('Existing target overwrite accepted')
        except ValueError:
            pass
        snapshot_result.update(isolatedDataRestored=True, initializationNotRepeated=True, sourceOverwriteRejected=True, existingTargetOverwriteRejected=True)
    print(json.dumps({'runtime': evidence, 'failedInitializationResumed': True, 'migrationExecutedOnce': True, 'literalEnvironmentPreserved': True, 'idempotentReplay': True, 'coldSnapshot': snapshot_result}))
finally:
    for job in reversed(jobs_to_cleanup):
        fingerprint = hashlib.sha256(json.dumps(job, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
        journal = root / job['instanceId'] / 'installation.json'
        if not journal.exists():
            journal = root / job['instanceId'] / 'restore-status.json'
        if journal.exists() and json.loads(journal.read_text()).get('fingerprint') == fingerprint:
            for container in docker(['ps', '-aq', '--filter', 'label=com.docker.compose.project=' + job['project']]).split():
                assert docker(['inspect', '-f', '{{index .Config.Labels "' + kernel.OWNER + '"}}', container]) == fingerprint, 'Cleanup ownership mismatch'
            for volume in job['volumes']:
                assert docker(['volume', 'inspect', '-f', '{{index .Labels "' + kernel.OWNER + '"}}', job['project'] + '_' + volume]) == fingerprint, 'Cleanup volume ownership mismatch'
            cleanup = {'services': {name: {'image': service['image']} for name, service in job['compose']['services'].items()}, 'volumes': job['compose'].get('volumes', {}), 'networks': job['compose'].get('networks', {})}
            command = ['docker', 'compose'] if subprocess.run(['docker', 'compose', 'version'], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL).returncode == 0 else ['docker-compose']
            subprocess.run(command + ['-p', job['project'], '-f', '-', 'down', '--volumes'], input=json.dumps(cleanup).encode(), stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=60, check=True)
            assert not docker(['ps', '-aq', '--filter', 'label=com.docker.compose.project=' + job['project']]), 'Probe cleanup failed'
